import json, os

ROOT = os.path.dirname(os.path.abspath(__file__))
INFO = {}

def put(key, rows=None, summary=None, wrong=None, date=None, note=None):
    d = INFO.setdefault(key, {})
    if rows: d.setdefault('rows', []).extend(rows)
    if summary: d['summary'] = summary
    if wrong: d['wrong'] = wrong
    if date: d['date'] = date
    if note: d['note'] = note

def kor(c, mx=None): return {'s': '국어', 'basis': '원점수', 'c': c, **({'max': mx} if mx else {})}
def mat(c, mx=None): return {'s': '수학', 'basis': '원점수', 'c': c, **({'max': mx} if mx else {})}
def eng(rates): return {'s': '영어', 'abs': [90, 80, 70, 60][:len(rates)], 'rates': rates}
def his(r1): return {'s': '한국사', 'abs': [40], 'rates': [r1]}

